import type {
  CharacterId,
  CharacterLevel,
  CharacterName,
  CharacterPackId,
  CharacterSchemaVersion,
  CharacterVariantRuleId,
  FeatDisplayId,
  FeatDisplaySection,
  PlayState,
  PlayStateId,
  SheetMode,
  SheetModeId,
  StoredCharacterDocument,
} from '@pioneer/character/domain';
import type { ContentPackId, VariantRuleId } from '@pioneer/rules/sdk';
import type { UserId, Version } from '@pioneer/shared/kernel';
import {
  boolean,
  index,
  integer,
  jsonb,
  pgTable,
  smallint,
  text,
  timestamp,
  uniqueIndex,
  uuid,
} from 'drizzle-orm/pg-core';

/**
 * Drizzle schema for the character aggregate. Migrations live in
 * apps/api/migrations. Every sort or filter a repository issues must be served
 * by an index here; the query-plan guard in the repository tests enforces it.
 *
 * A character is stored as its `CharacterDocument`. `name`, `level` and `owner_id` are copies of the document's,
 * kept in step by the repository in the same write, so lists sort and filter on columns; nothing queries into
 * `document`.
 */
export const characters = pgTable(
  'characters',
  {
    // UUIDv4, generated by the application (newId()).
    id: uuid().$type<CharacterId>().primaryKey(),
    version: integer().$type<Version>().notNull(),
    // A user id. Its foreign key to users (on delete cascade) is in migration 0005, not here;
    // Identity's tables are outside this context's module boundary.
    ownerId: uuid().$type<UserId>().notNull(),
    name: text().$type<CharacterName>().notNull(),
    level: smallint().$type<CharacterLevel>().notNull(),
    // The document's own `schemaVersion`, as a column so old rows can be counted without reading documents.
    schemaVersion: smallint().$type<CharacterSchemaVersion>().notNull(),
    // Decoded with `decodeCharacterDocument`, which upgrades an older version; saves write the current one.
    document: jsonb().$type<StoredCharacterDocument>().notNull(),
    // Strings, not Date: Date is banned; rows are converted to Temporal.Instant.
    createdAt: timestamp({ withTimezone: true, mode: 'string' }).notNull(),
    updatedAt: timestamp({ withTimezone: true, mode: 'string' }).notNull(),
    // Set when the owner archives the character (ADR-0062); null is live. A row is never deleted.
    // The owner's foreign key to users (migration 0023) is restrict. Never written by a build save.
    archivedAt: timestamp({ withTimezone: true, mode: 'string' }),
  },
  (table) => [
    // One index per CharacterSort option within an owner's characters, ending in id (the tie-breaker).
    // Asc and desc both use it (backward index scan).
    index('characters_owner_created_at_id_idx').on(table.ownerId, table.createdAt, table.id),
    index('characters_owner_name_id_idx').on(table.ownerId, table.name, table.id),
  ],
);

/**
 * The tab each user last had open on each character's sheet (ADR-0052), one row once they first switch tabs. Not part
 * of the character: switching tabs never bumps its version. `id` is the row's own, for the audit trail; lookups and
 * the upsert go through the unique (user, character) index. The user's foreign key to users (on delete cascade) is in
 * the migration, as for `owner_id`; deleting the character deletes its rows too.
 */
export const characterSheetModes = pgTable(
  'character_sheet_modes',
  {
    id: uuid().$type<SheetModeId>().primaryKey(),
    userId: uuid().$type<UserId>().notNull(),
    characterId: uuid()
      .$type<CharacterId>()
      .notNull()
      .references(() => characters.id, { onDelete: 'cascade' }),
    mode: text().$type<SheetMode>().notNull(),
    updatedAt: timestamp({ withTimezone: true, mode: 'string' }).notNull(),
  },
  (table) => [
    uniqueIndex('character_sheet_modes_user_character_idx').on(table.userId, table.characterId),
    // Serves the cascade when a character is deleted.
    index('character_sheet_modes_character_idx').on(table.characterId),
  ],
);

/**
 * Where a user shows a character's grant-only feats (ADR-0052): a row per (user, character, section), a display
 * preference that is not part of the character document. `id` is the row's own, for the audit trail; lookups and the
 * upsert go through the unique (user, character, section) index. The user's foreign key to users (on delete cascade)
 * is in the migration, as for `owner_id`; deleting the character deletes its rows too.
 */
export const characterFeatDisplays = pgTable(
  'character_feat_displays',
  {
    id: uuid().$type<FeatDisplayId>().primaryKey(),
    userId: uuid().$type<UserId>().notNull(),
    characterId: uuid()
      .$type<CharacterId>()
      .notNull()
      .references(() => characters.id, { onDelete: 'cascade' }),
    section: text().$type<FeatDisplaySection>().notNull(),
    showGrantOnly: boolean().notNull(),
    updatedAt: timestamp({ withTimezone: true, mode: 'string' }).notNull(),
  },
  (table) => [
    uniqueIndex('character_feat_displays_user_character_section_idx').on(
      table.userId,
      table.characterId,
      table.section,
    ),
    // Serves the cascade when a character is deleted.
    index('character_feat_displays_character_idx').on(table.characterId),
  ],
);

/**
 * A character's play state (#343), apart from its build: play edits bump `play_revision` only, and build saves never
 * write it (ADR-0022). One row per character, inserted with it. `id` is the row's own, for the audit trail; lookups go
 * through the unique character index, which also serves the cascade when a character is deleted.
 */
export const characterPlay = pgTable(
  'character_play',
  {
    id: uuid().$type<PlayStateId>().primaryKey(),
    characterId: uuid()
      .$type<CharacterId>()
      .notNull()
      .references(() => characters.id, { onDelete: 'cascade' }),
    playRevision: integer().$type<Version>().notNull(),
    state: jsonb().$type<PlayState>().notNull(),
    createdAt: timestamp({ withTimezone: true, mode: 'string' }).notNull(),
    updatedAt: timestamp({ withTimezone: true, mode: 'string' }).notNull(),
  },
  (table) => [uniqueIndex('character_play_character_idx').on(table.characterId)],
);

/**
 * The content packs a character has enabled, one row each, used while it is in no campaign (a character in a campaign
 * uses the campaign's packs and ignores these). The audit log keys rows by `id`, so an enablement has its own id. The
 * foreign keys on `pack_id` (to content_packs, on delete cascade) and `enabled_by` (to users, on delete set null) are in
 * the migration, as the rules and identity contexts' tables are outside this one's boundary; deleting the character
 * deletes its rows too.
 */
export const characterPacks = pgTable(
  'character_packs',
  {
    id: uuid().$type<CharacterPackId>().primaryKey(),
    characterId: uuid()
      .$type<CharacterId>()
      .notNull()
      .references(() => characters.id, { onDelete: 'cascade' }),
    packId: uuid().$type<ContentPackId>().notNull(),
    // Null once the user who enabled it is deleted.
    enabledBy: uuid().$type<UserId>(),
    enabledAt: timestamp({ withTimezone: true, mode: 'string' }).notNull(),
  },
  (table) => [
    // A character enables a pack once; also serves the character's list and the cascade when it is deleted.
    uniqueIndex('character_packs_character_pack_idx').on(table.characterId, table.packId),
    // The characters enabling a pack; also serves the cascade when the pack is deleted.
    index('character_packs_pack_idx').on(table.packId),
    // Serves clearing `enabled_by` when the user is deleted.
    index('character_packs_enabled_by_idx').on(table.enabledBy),
  ],
);

/**
 * The variant rules a character has enabled, one row each, used while it is in no campaign (a character in a campaign
 * uses the campaign's variant rules and ignores these; ADR-0061). The audit log keys rows by `id`, so an enablement has
 * its own id. `variant_id` is a variant-rule content entry's id; it has no foreign key, since a pack going away must not
 * delete the choice: a variant rule whose pack is not in force is left out when the set is read, and comes back with
 * its pack. The foreign key on `enabled_by` (to users, on delete set null) is in the migration, as identity's tables
 * are outside this context's boundary; deleting the character deletes its rows too.
 */
export const characterVariantRules = pgTable(
  'character_variant_rules',
  {
    id: uuid().$type<CharacterVariantRuleId>().primaryKey(),
    characterId: uuid()
      .$type<CharacterId>()
      .notNull()
      .references(() => characters.id, { onDelete: 'cascade' }),
    variantId: uuid().$type<VariantRuleId>().notNull(),
    // Null once the user who enabled it is deleted.
    enabledBy: uuid().$type<UserId>(),
    enabledAt: timestamp({ withTimezone: true, mode: 'string' }).notNull(),
  },
  (table) => [
    // A character enables a variant rule once; also serves the character's list and the cascade when it is deleted.
    uniqueIndex('character_variant_rules_character_variant_idx').on(table.characterId, table.variantId),
    // Serves clearing `enabled_by` when the user is deleted.
    index('character_variant_rules_enabled_by_idx').on(table.enabledBy),
  ],
);
