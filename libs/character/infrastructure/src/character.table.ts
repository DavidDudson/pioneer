import type {
  CharacterId,
  CharacterLevel,
  CharacterName,
  CharacterSchemaVersion,
  SheetMode,
  SheetModeId,
  StoredCharacterDocument,
} from '@pioneer/character/domain';
import type { UserId, Version } from '@pioneer/shared/kernel';
import { index, integer, jsonb, pgTable, smallint, text, timestamp, uniqueIndex, uuid } from 'drizzle-orm/pg-core';

/**
 * Drizzle schema for the character aggregate. Migrations live in
 * apps/api/migrations. Every sort or filter a repository issues must be served
 * by an index here; the query-plan guard in the repository tests enforces it.
 *
 * A character is stored as its `CharacterDocument`. `name`, `level` and `owner_id` are copies of the document's,
 * kept in step by the repository in the same write, so lists sort and filter on columns; nothing queries into
 * `document`.
 */
export const characters = pgTable(
  'characters',
  {
    // UUIDv4, generated by the application (newId()).
    id: uuid().$type<CharacterId>().primaryKey(),
    version: integer().$type<Version>().notNull(),
    // A user id. Its foreign key to users (on delete cascade) is in migration 0005, not here;
    // Identity's tables are outside this context's module boundary.
    ownerId: uuid().$type<UserId>().notNull(),
    name: text().$type<CharacterName>().notNull(),
    level: smallint().$type<CharacterLevel>().notNull(),
    // The document's own `schemaVersion`, as a column so old rows can be counted without reading documents.
    schemaVersion: smallint().$type<CharacterSchemaVersion>().notNull(),
    // Decoded with `decodeCharacterDocument`, which upgrades an older version; saves write the current one.
    document: jsonb().$type<StoredCharacterDocument>().notNull(),
    // Strings, not Date: Date is banned; rows are converted to Temporal.Instant.
    createdAt: timestamp({ withTimezone: true, mode: 'string' }).notNull(),
    updatedAt: timestamp({ withTimezone: true, mode: 'string' }).notNull(),
  },
  (table) => [
    // One index per CharacterSort option within an owner's characters, ending in id (the tie-breaker).
    // Asc and desc both use it (backward index scan).
    index('characters_owner_created_at_id_idx').on(table.ownerId, table.createdAt, table.id),
    index('characters_owner_name_id_idx').on(table.ownerId, table.name, table.id),
  ],
);

/**
 * The tab each user last had open on each character's sheet (ADR-0052), one row once they first switch tabs. Not part
 * of the character: switching tabs never bumps its version. `id` is the row's own, for the audit trail; lookups and
 * the upsert go through the unique (user, character) index. The user's foreign key to users (on delete cascade) is in
 * the migration, as for `owner_id`; deleting the character deletes its rows too.
 */
export const characterSheetModes = pgTable(
  'character_sheet_modes',
  {
    id: uuid().$type<SheetModeId>().primaryKey(),
    userId: uuid().$type<UserId>().notNull(),
    characterId: uuid()
      .$type<CharacterId>()
      .notNull()
      .references(() => characters.id, { onDelete: 'cascade' }),
    mode: text().$type<SheetMode>().notNull(),
    updatedAt: timestamp({ withTimezone: true, mode: 'string' }).notNull(),
  },
  (table) => [
    uniqueIndex('character_sheet_modes_user_character_idx').on(table.userId, table.characterId),
    // Serves the cascade when a character is deleted.
    index('character_sheet_modes_character_idx').on(table.characterId),
  ],
);
